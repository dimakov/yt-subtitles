// Runs in the YouTube page's own JavaScript world (manifest "world": "MAIN").
//
// It owns everything that must happen as the YouTube page: reading the
// player's caption track list, remembering the proof-of-origin (PO) token the
// player attaches to its own timed-text requests, and fetching timed text from
// the youtube.com origin. The popup calls window.__ytSubtitleDownloader through
// chrome.scripting.executeScript and only receives JSON-safe values back.
(() => {
  const API_NAME = '__ytSubtitleDownloader';
  const API_VERSION = 1;
  if ((window[API_NAME]?.version ?? 0) >= API_VERSION) return;

  const MAX_REMEMBERED_VIDEOS = 20;
  const TOKEN_WAIT_MS = 8000;
  // A stalled request fails over to the next strategy instead of hanging the popup.
  const REQUEST_TIMEOUT_MS = 15000;
  // Parameters that pick the track or output format. They always come from the
  // target track, never from the captured player request.
  const TRACK_PARAMS = new Set(['v', 'lang', 'tlang', 'kind', 'name', 'fmt']);
  // Innertube clients whose caption URLs work without a PO token.
  const INNERTUBE_CLIENTS = [
    { name: 'ANDROID', version: '20.10.38' },
    { name: 'IOS', version: '20.10.4' },
  ];

  /** videoId -> URL of the player's latest timed-text request that carried a PO token. */
  const tokenRequests = new Map();

  function rememberRequest(name) {
    if (typeof name !== 'string' || !name.includes('/api/timedtext')) return;
    let url;
    try {
      url = new URL(name, location.origin);
    } catch {
      return;
    }
    const videoId = url.searchParams.get('v');
    if (!videoId || !url.searchParams.get('pot')) return;
    tokenRequests.delete(videoId);
    tokenRequests.set(videoId, url);
    while (tokenRequests.size > MAX_REMEMBERED_VIDEOS) {
      tokenRequests.delete(tokenRequests.keys().next().value);
    }
  }

  // Resource timing sees the player's XHRs without patching XMLHttpRequest or
  // fetch, and observers keep receiving entries after the timing buffer fills.
  try {
    new PerformanceObserver((list) => {
      for (const entry of list.getEntries()) rememberRequest(entry.name);
    }).observe({ type: 'resource', buffered: true });
  } catch {
    // Without the observer only Innertube and the CC toggle remain.
  }

  function currentVideoId() {
    const url = new URL(location.href);
    if (url.pathname === '/watch') return url.searchParams.get('v');
    const match = url.pathname.match(/^\/(?:shorts|live|embed)\/([\w-]{11})/);
    return match ? match[1] : null;
  }

  function findPlayer(videoId) {
    const candidates = new Set([
      document.getElementById('movie_player'),
      document.getElementById('shorts-player'),
      ...document.querySelectorAll('.html5-video-player'),
    ]);
    for (const element of candidates) {
      try {
        if (element?.getPlayerResponse?.()?.videoDetails?.videoId === videoId) return element;
      } catch {
        // A player that is still initialising can throw; try the next one.
      }
    }
    return null;
  }

  function pagePlayerResponse(videoId) {
    const player = findPlayer(videoId);
    if (player) return player.getPlayerResponse();
    // Only valid for the first video of a page load; SPA navigation leaves it stale.
    const initial = window.ytInitialPlayerResponse;
    return initial?.videoDetails?.videoId === videoId ? initial : null;
  }

  async function innertubePlayerResponse(videoId, client) {
    const hl = window.ytcfg?.get?.('HL') || document.documentElement.lang || 'en';
    const response = await fetch('/youtubei/v1/player?prettyPrint=false', {
      method: 'POST',
      // These clients are not the signed-in web client; sending the user's
      // cookies with them is unnecessary.
      credentials: 'omit',
      signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        context: { client: { clientName: client.name, clientVersion: client.version, hl } },
        videoId,
      }),
    });
    if (!response.ok) throw new Error(`player request failed (HTTP ${response.status})`);
    const data = await response.json();
    if (data?.videoDetails?.videoId !== videoId) {
      throw new Error(data?.playabilityStatus?.reason || data?.playabilityStatus?.status || 'no video details');
    }
    return data;
  }

  function captionTracks(response) {
    return response?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  }

  function isAutoGenerated(track) {
    // The ANDROID client omits "kind"; its vssId still starts with "a.".
    return track.kind === 'asr' || String(track.vssId ?? '').startsWith('a.');
  }

  function findTrack(response, vssId, languageCode, kind) {
    const tracks = captionTracks(response);
    return (
      tracks.find((track) => track.vssId === vssId) ??
      tracks.find(
        (track) =>
          track.languageCode === languageCode && (isAutoGenerated(track) ? 'asr' : 'standard') === kind,
      ) ??
      null
    );
  }

  function textOf(value) {
    if (!value) return '';
    if (typeof value.simpleText === 'string') return value.simpleText;
    return Array.isArray(value.runs) ? value.runs.map((run) => run.text ?? '').join('') : '';
  }

  function describeVideo(response, source) {
    const details = response.videoDetails ?? {};
    const renderer = response.captions?.playerCaptionsTracklistRenderer;
    return {
      videoId: details.videoId,
      title: details.title ?? '',
      author: details.author ?? '',
      lengthSeconds: Number(details.lengthSeconds) || 0,
      source,
      tracks: captionTracks(response).map((track) => ({
        vssId: track.vssId ?? '',
        languageCode: track.languageCode ?? '',
        name: textOf(track.name) || track.languageCode || 'Unknown',
        kind: isAutoGenerated(track) ? 'asr' : 'standard',
        isTranslatable: Boolean(track.isTranslatable),
      })),
      translationLanguages: (renderer?.translationLanguages ?? []).map((language) => ({
        languageCode: language.languageCode,
        name: textOf(language.languageName) || language.languageCode,
      })),
    };
  }

  /** Track list for the video in this tab, or { reason } when there is none. */
  async function getVideoInfo() {
    const videoId = currentVideoId();
    if (!videoId) return { reason: 'not-video' };
    let response = pagePlayerResponse(videoId);
    let source = 'page';
    if (!captionTracks(response).length) {
      // The page copy can be missing (an ad is playing, the player is still
      // loading) or omit captions, so ask Innertube before giving up.
      for (const client of INNERTUBE_CLIENTS) {
        try {
          const fallback = await innertubePlayerResponse(videoId, client);
          if (captionTracks(fallback).length || !response) {
            response = fallback;
            source = client.name;
          }
          break;
        } catch {
          // Try the next client.
        }
      }
    }
    if (!response) return { reason: 'no-player', videoId };
    return { video: describeVideo(response, source) };
  }

  async function fetchTimedText(baseUrl, { tlang, withCookies }) {
    const url = new URL(baseUrl, location.origin);
    url.searchParams.set('fmt', 'json3');
    if (tlang) url.searchParams.set('tlang', tlang);
    else url.searchParams.delete('tlang');
    const response = await fetch(url.href, {
      credentials: withCookies ? 'same-origin' : 'omit',
      signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
    });
    if (response.status === 429) throw new Error('rate-limited by YouTube (HTTP 429)');
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const text = await response.text();
    // YouTube answers 200 with an empty body when it wants a PO token.
    return text.trimStart().startsWith('{') ? text : null;
  }

  function withPlayerToken(baseUrl, tokenUrl) {
    const url = new URL(baseUrl, location.origin);
    for (const [key, value] of tokenUrl.searchParams) {
      if (!TRACK_PARAMS.has(key) && !url.searchParams.has(key)) url.searchParams.set(key, value);
    }
    return url.href;
  }

  const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

  async function waitFor(check, timeoutMs) {
    const deadline = Date.now() + timeoutMs;
    for (;;) {
      const value = check();
      if (value || Date.now() >= deadline) return value ?? null;
      await delay(100);
    }
  }

  /**
   * Makes the player load captions so its timed-text request (and PO token)
   * shows up in resource timing, then puts the CC button back as it was.
   */
  async function requestTokenFromPlayer(videoId) {
    const player = findPlayer(videoId);
    const button = player?.querySelector('.ytp-subtitles-button');
    if (!button) return null;
    const previous = tokenRequests.get(videoId);
    const wasOn = button.getAttribute('aria-pressed') === 'true';
    if (wasOn) {
      // Captions already show but no request was seen (the script arrived
      // late); turning them off and on again makes the player ask anew.
      button.click();
      await delay(250);
    }
    button.click();
    const fresh = await waitFor(() => {
      const url = tokenRequests.get(videoId);
      return url && url !== previous ? url : null;
    }, TOKEN_WAIT_MS);
    if (!wasOn) button.click();
    return fresh;
  }

  /**
   * Downloads one track as json3 text. Tries, in order: the PO token already
   * captured from the player; the token-free Innertube clients; and finally a
   * fresh token by toggling captions. Translations are rate-limited without a
   * token, so for them the fresh token comes before Innertube.
   */
  async function fetchCaptions({ videoId, vssId, languageCode, kind, tlang = '' }) {
    if (videoId !== currentVideoId()) {
      throw new Error('This tab now shows a different video. Open the popup again.');
    }
    const pageTrack = findTrack(pagePlayerResponse(videoId), vssId, languageCode, kind);
    const viaToken = (getToken) => async () => {
      const token = await getToken();
      if (!token) throw new Error('the player did not request captions');
      return fetchTimedText(withPlayerToken(pageTrack.baseUrl, token), { tlang, withCookies: true });
    };

    const strategies = [];
    if (pageTrack && tokenRequests.has(videoId)) {
      strategies.push(['player token', viaToken(() => tokenRequests.get(videoId))]);
    }
    const innertube = INNERTUBE_CLIENTS.map((client) => [
      client.name,
      async () => {
        const track = findTrack(await innertubePlayerResponse(videoId, client), vssId, languageCode, kind);
        if (!track) throw new Error('track not offered');
        return fetchTimedText(track.baseUrl, { tlang, withCookies: false });
      },
    ]);
    const fresh = pageTrack ? [['fresh player token', viaToken(() => requestTokenFromPlayer(videoId))]] : [];
    strategies.push(...(tlang ? [...fresh, ...innertube] : [...innertube, ...fresh]));

    const failures = [];
    for (const [label, run] of strategies) {
      try {
        const text = await run();
        if (text) return { text, source: label };
        failures.push(`${label}: empty response`);
      } catch (error) {
        failures.push(`${label}: ${error?.message ?? error}`);
      }
    }
    throw new Error(`YouTube did not return these subtitles (${failures.join('; ') || 'track not found'}).`);
  }

  Object.defineProperty(window, API_NAME, {
    value: Object.freeze({ version: API_VERSION, getVideoInfo, fetchCaptions }),
    configurable: true,
  });
})();
